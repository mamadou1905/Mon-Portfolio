const languageButton = document.querySelector("#languageToggle");
const themeButton = document.querySelector("#themeToggle");
const themeIcon = document.querySelector("#themeIcon");
const menuButton = document.querySelector(".menu-toggle");
const nav = document.querySelector(".nav");

function setLanguage(language) {
  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (translations[language][key]) element.innerHTML = translations[language][key];
  });
  languageButton.textContent = language === "fr" ? "EN" : "FR";
  document.title = language === "fr"
    ? "Mamadou Dian Diallo — Software Engineer"
    : "Mamadou Dian Diallo — Software Engineer";
  localStorage.setItem("portfolio-language", language);
}

function setTheme(theme) {
  document.documentElement.dataset.theme = theme;
  themeIcon.textContent = theme === "dark" ? "☀" : "☾";
  themeButton.setAttribute("aria-label", theme === "dark" ? "Switch to light mode" : "Switch to dark mode");
  localStorage.setItem("portfolio-theme", theme);
}

languageButton.addEventListener("click", () => {
  setLanguage(document.documentElement.lang === "fr" ? "en" : "fr");
});
themeButton.addEventListener("click", () => {
  setTheme(document.documentElement.dataset.theme === "dark" ? "light" : "dark");
});

menuButton.addEventListener("click", () => {
  const opened = nav.classList.toggle("open");
  menuButton.setAttribute("aria-expanded", String(opened));
});
nav.querySelectorAll("a").forEach((link) => link.addEventListener("click", () => {
  nav.classList.remove("open");
  menuButton.setAttribute("aria-expanded", "false");
}));

setLanguage(localStorage.getItem("portfolio-language") || "fr");
setTheme(localStorage.getItem("portfolio-theme") || "light");
document.querySelector("#year").textContent = new Date().getFullYear();
